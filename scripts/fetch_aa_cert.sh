#!/usr/bin/env bash
# Fetch the Android Auto head-unit certificate + RSA private key from upstream
# aasdk and generate device/AaHuCert.gen.h (git-ignored).
#
# A real phone only completes the AA TLS handshake against this specific
# Google-registered head-unit cert (issuer "Google Automotive Link"); a
# self-signed cert is rejected. carsh does not redistribute it: the cert and key
# live in aasdk (GPLv3, https://github.com/f1xpl/aasdk, src/Messenger/Cryptor.cpp)
# and this script pulls them from a pinned commit, checks them against known
# SHA-256 digests, and emits the header that device/AaHuCert.h includes.
#
# Usage: scripts/fetch_aa_cert.sh            (needs curl + python3)
set -euo pipefail

AASDK_COMMIT="9ee5283245a630afce3a441696b9dde484ecbcd9"
URL="https://raw.githubusercontent.com/f1xpl/aasdk/${AASDK_COMMIT}/src/Messenger/Cryptor.cpp"
CERT_DER_SHA256="1c0e0ef9e672dd1a63ab4d61afaa8996a57ca7aa966d1922b97d8f9385ea3c35"
KEY_PEM_SHA256="9e837a172a1eef5b05cda9df9d086753639648a17f76c2c939bcbd094aa972f2"

TOP="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$TOP/device/AaHuCert.gen.h"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "Fetching aasdk Cryptor.cpp @ ${AASDK_COMMIT:0:12} ..."
curl -fsSL "$URL" -o "$TMP/Cryptor.cpp"

python3 -I - "$TMP/Cryptor.cpp" "$OUT.tmp" "$CERT_DER_SHA256" "$KEY_PEM_SHA256" <<'PY'
import base64, hashlib, re, sys

src_path, out_path, want_cert, want_key = sys.argv[1:5]
src = open(src_path, encoding="utf-8").read()

def pem_block(label):
    m = re.search(r"-----BEGIN %s-----(.*?)-----END %s-----" % (label, label), src, re.S)
    if not m:
        sys.exit("fetch_aa_cert: no %s block in Cryptor.cpp" % label)
    # Source is a C++ string with "\n\" line continuations; keep base64 chars only.
    body = re.sub(r"\\n|[^A-Za-z0-9+/=]", "", m.group(1))
    return body

cert_der = base64.b64decode(pem_block("CERTIFICATE"))
key_b64 = pem_block("RSA PRIVATE KEY")
key_pem = ("-----BEGIN RSA PRIVATE KEY-----\n"
           + "".join(key_b64[i:i + 64] + "\n" for i in range(0, len(key_b64), 64))
           + "-----END RSA PRIVATE KEY-----\n")

for what, data, want in (("certificate", cert_der, want_cert),
                         ("private key", key_pem.encode(), want_key)):
    got = hashlib.sha256(data).hexdigest()
    if got != want:
        sys.exit("fetch_aa_cert: %s SHA-256 mismatch (got %s, want %s)" % (what, got, want))

lines = [
    "// GENERATED by scripts/fetch_aa_cert.sh from aasdk src/Messenger/Cryptor.cpp",
    "// (GPLv3). Do not edit; do not commit (git-ignored). See device/AaHuCert.h.",
    "#ifndef _carsh_aa_hu_cert_gen_h",
    "#define _carsh_aa_hu_cert_gen_h",
    "",
    "#include <cstddef>",
    "",
    "namespace carsh::device {",
    "",
    "inline constexpr unsigned char kHuCertDer[] = {",
]
for i in range(0, len(cert_der), 12):
    lines.append("    " + " ".join("0x%02x," % b for b in cert_der[i:i + 12]))
lines += [
    "};",
    "inline constexpr std::size_t kHuCertDerLen = sizeof(kHuCertDer);",
    "",
    "inline constexpr char kHuKeyPem[] =",
]
lines += ['    "%s\\n"' % l for l in key_pem.rstrip("\n").split("\n")]
lines[-1] += ";"
lines += [
    "inline constexpr std::size_t kHuKeyPemLen = sizeof(kHuKeyPem);  // includes NUL",
    "",
    "}  // namespace carsh::device",
    "",
    "#endif  // _carsh_aa_hu_cert_gen_h",
    "",
]
open(out_path, "w", encoding="utf-8").write("\n".join(lines))
PY

mv "$OUT.tmp" "$OUT"
echo "Wrote $OUT (cert + key verified against pinned SHA-256)."

// AaHuCert — the head-unit X.509 certificate + RSA private key the Android Auto
// TLS handshake presents to the phone (the HU is the SSL client; AA uses mutual
// auth, so the phone requests this cert). Embedded as raw DER (cert) + PEM (key)
// so the bare-metal image needs no filesystem to load them.
//
// !!! PLACEHOLDER TEST CERT — NOT THE GOOGLE-REGISTERED AASDK CERT !!!
// This is a locally generated self-signed RSA-2048 cert used to host-test the
// mbedTLS plumbing (in-memory client<->server handshake round-trip). A real
// phone will REJECT it: Android Auto only completes the handshake against the
// specific aasdk / JVC-Kenwood head-unit certificate registered with Google's AA
// program. Before the bench TLS pass [hw], replace kHuCertDer/kHuKeyPem with the
// real cert+key from dylant9/head_unit:main/aa_crypto.c (aa_cert_der_fallback[] +
// aa_private_key_pem_fallback). That cert uses a non-standard UTCTime (-0700)
// offset mbedTLS rejects — AaCryptoMbedTls handles it via the raw-cert bypass
// (see loadOwnCert), so only the bytes below need swapping.
